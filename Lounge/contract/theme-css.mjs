// The stylesheet's theme blocks, generated from the same tables the engine reads, so CSS and palette cannot drift:
//   THEME-FALLBACK: Original Signature (what shows before the engine has run, or if scripts are blocked)
//   THEME-PANELS:   which surfaces re-declare their colours from the panel copy of the palette (cards, sidebar, top bar, sheets, dialogs)
// build.mjs writes them into index.html; theme-schemes.test.js fails if index.html holds anything else.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const dir = path.dirname(fileURLToPath(import.meta.url));
const read = (f) => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
export function loadEngine() {
  const themes = read('themes.json'), schemes = read('theme-schemes.json');
  const contract = { ...themes, schemes: schemes.themes, roles: schemes.roles, generator: schemes.generator };
  const win = {}; vm.runInNewContext(fs.readFileSync(path.join(dir, '..', 'theme-engine.js'), 'utf8'), { window: win, Intl, Math, Number, String, Date, Set, Map, Array, Object, JSON, isFinite, parseInt, setInterval: () => 0, document: undefined });
  return { contract, E: win.CocoThemeEngine(contract) };
}
export const PANEL_SELECTORS = ['.card2', '.kpi', '.fwrap', '.rail', '.topbar', '.bottom', '.panel', '.results', '.askdrawer', '.sheet-card', '.menu-p', 'dialog', '.form', '.gate .card', '.th-card', '.thbar'];
const decl = (o) => Object.entries(o).map(([k, v]) => k + ': ' + v + ';').join(' ');
export const FALLBACK = { start: '/* THEME-FALLBACK-START', end: '/* THEME-FALLBACK-END */' };
export const PANELS = { start: '/* THEME-PANELS-START', end: '/* THEME-PANELS-END */' };
export function fallbackBlock(E) {
  return '/* THEME-FALLBACK-START (generated by contract/build.mjs from the Original Signature tables; edit themes.json, never this block) */\n'
    + ':root { ' + decl(E.cssFor('signature', 'light')) + ' color-scheme: light; }\n'
    + '@media (prefers-color-scheme: dark) { :root:not([data-theme="light"]) { ' + decl(E.cssFor('signature', 'dark')) + ' color-scheme: dark; } }\n'
    + ':root[data-theme="dark"] { ' + decl(E.cssFor('signature', 'dark')) + ' color-scheme: dark; }\n/* THEME-FALLBACK-END */';
}
export function panelsBlock(E) {
  return '/* THEME-PANELS-START (generated) */\n' + PANEL_SELECTORS.join(',\n') + ' {\n  ' + E.PANEL_VARS.map((v) => v + ': var(--p-' + v.slice(2) + ');').join('\n  ') + '\n  color: var(--on-surface); color-scheme: var(--p-scheme, light);   /* inherited text colour and native controls follow the panel, not the page */\n}\n/* THEME-PANELS-END */';
}
export const swap = (text, m, block) => { const a = text.indexOf(m.start), z = text.indexOf(m.end); if (a < 0 || z < a) throw new Error('markers missing in index.html: ' + m.start); return text.slice(0, a) + block + text.slice(z + m.end.length); };
