// Chrome blocks CSS mask SVGs loaded from file:// (CORS, origin "null"), so the theme's
// shapes vanish when index.html is opened by double-clicking. This bakes them into
// theme/shapes-inline.css as data URIs. Re-run after updating the theme folder.
// Run: node inline-shapes.mjs
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, 'theme', 'dist', 'shapes');

const rules = readdirSync(dir)
  .filter(f => f.endsWith('.svg') && f !== 'morph-loop.svg')
  .map(f => {
    const data = Buffer.from(readFileSync(join(dir, f))).toString('base64');
    return `.mu-shape--${f.replace(/\.svg$/, '')} { --_m: url('data:image/svg+xml;base64,${data}'); }`;
  });

writeFileSync(join(here, 'theme', 'shapes-inline.css'),
  `/* Generated by inline-shapes.mjs — do not edit. Makes the theme's shapes work offline on file://. */\n${rules.join('\n')}\n`);

console.log(`OK ${rules.length} shapes inlined`);
