// Needs: npm i @material/material-color-utilities@0.3.0 (0.4+ is broken under Node ESM). Run from a folder that has node_modules.
﻿// Vivi token generator: M3 roles from tonal palettes -> tokens.css per kit. Run: node gen.mjs
import { createRequire } from 'node:module'; const { TonalPalette, argbFromHex, hexFromArgb } = createRequire(import.meta.url)('@material/material-color-utilities');
import fs from 'node:fs';
const OUT = 'C:/Users/Lenovo/Good Space/Coco/Design Atelier/Themes';

const kits = {
  'Document Toolkit': {
    p: 'dt', hues: { primary: [34, 96], secondary: [250, 14], tertiary: [195, 40], neutral: [245, 3], nv: [245, 8], error: [25, 84] },
    lightPrimary: 46, // brighter cinnabar than M3 default 40, still AA with white
    shape: { xs: 2, sm: 4, md: 8, lg: 12, xl: 20 },
    fonts: { display: "'Newsreader', 'Georgia', serif", body: "'Schibsted Grotesk', system-ui, sans-serif", mono: "'JetBrains Mono', ui-monospace, monospace" },
    brand: (L, D) => ({ 'paper-grain': 'rgba(24,32,48,.035)', 'accent-glow': 'rgba(222,86,24,.28)' }),
  },
  'Coco Notes': {
    p: 'cn', hues: { primary: [335, 90], secondary: [175, 30], tertiary: [285, 50], neutral: [335, 4], nv: [335, 8], error: [25, 84] },
    lightPrimary: 46,
    shape: { xs: 8, sm: 14, md: 20, lg: 28, xl: 40 },
    fonts: { display: "'Bricolage Grotesque', system-ui, sans-serif", body: "'DM Sans', system-ui, sans-serif", mono: "'DM Mono', ui-monospace, monospace" },
    brand: () => ({ 'capture-glow': 'rgba(214,40,140,.35)' }),
  },
  'Candidate Aurora': {
    p: 'ca', hues: { primary: [172, 56], secondary: [285, 46], tertiary: [345, 52], neutral: [275, 7], nv: [275, 12], error: [25, 84] },
    lightPrimary: 36,
    shape: { xs: 8, sm: 16, md: 24, lg: 32, xl: 48 },
    fonts: { display: "'Bodoni Moda', 'Didot', serif", body: "'Manrope', system-ui, sans-serif", mono: "'Martian Mono', ui-monospace, monospace" },
    brand: () => ({ 'aurora-a': '#2fe0b4', 'aurora-b': '#8b5cf6', 'aurora-c': '#ff5fa8' }),
  },
};

const lum = (h) => { const n = argbFromHex(h); const c = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((v) => { v /= 255; return v <= .03928 ? v / 12.92 : ((v + .055) / 1.055) ** 2.4; }); return .2126 * c[0] + .7152 * c[1] + .0722 * c[2]; };
const ratio = (a, b) => { const x = lum(a), y = lum(b); return (Math.max(x, y) + .05) / (Math.min(x, y) + .05); };

const report = [];
for (const [name, k] of Object.entries(kits)) {
  const P = {}; for (const r of ['primary', 'secondary', 'tertiary', 'error']) P[r] = TonalPalette.fromHueAndChroma(...k.hues[r]);
  P.n = TonalPalette.fromHueAndChroma(...k.hues.neutral); P.nv = TonalPalette.fromHueAndChroma(...k.hues.nv);
  const t = (p, n) => hexFromArgb(P[p].tone(n));
  const accent = (r, lt, dt) => ({ light: [t(r, r === 'primary' ? k.lightPrimary : lt), t(r, 100), t(r, 90), t(r, 10)], dark: [t(r, 80), t(r, 20), t(r, 30), t(r, 90)] });
  const roles = { light: {}, dark: {} };
  for (const m of ['light', 'dark']) {
    const R = roles[m];
    for (const r of ['primary', 'secondary', 'tertiary', 'error']) { const a = accent(r, 40)[m]; R[r] = a[0]; R['on-' + r] = a[1]; R[r + '-container'] = a[2]; R['on-' + r + '-container'] = a[3]; }
    const L = m === 'light';
    Object.assign(R, {
      surface: t('n', L ? 98 : 6), 'surface-dim': t('n', L ? 87 : 6), 'surface-bright': t('n', L ? 98 : 24),
      'surface-container-lowest': t('n', L ? 100 : 4), 'surface-container-low': t('n', L ? 96 : 10), 'surface-container': t('n', L ? 94 : 12),
      'surface-container-high': t('n', L ? 92 : 17), 'surface-container-highest': t('n', L ? 90 : 22),
      'on-surface': t('n', L ? 10 : 90), 'on-surface-variant': t('nv', L ? 30 : 80), outline: t('nv', L ? 50 : 60), 'outline-variant': t('nv', L ? 80 : 30),
      background: t('n', L ? 98 : 6), 'on-background': t('n', L ? 10 : 90),
      'inverse-surface': t('n', L ? 20 : 90), 'inverse-on-surface': t('n', L ? 95 : 20), 'inverse-primary': t('primary', L ? 80 : 40),
      'surface-tint': R.primary, scrim: '#000000', shadow: '#000000',
    });
    for (const [a, b] of [['primary', 'on-primary'], ['primary-container', 'on-primary-container'], ['secondary', 'on-secondary'], ['secondary-container', 'on-secondary-container'], ['tertiary', 'on-tertiary'], ['tertiary-container', 'on-tertiary-container'], ['surface', 'on-surface'], ['surface', 'on-surface-variant'], ['surface-container-highest', 'on-surface']])
      report.push([name, m, a + '/' + b, ratio(R[a], R[b]).toFixed(2)]);
  }
  const block = (R, indent = '  ') => Object.entries(R).map(([n, v]) => `${indent}--md-sys-color-${n}: ${v};`).join('\n');
  const brand = k.brand(roles.light, roles.dark);
  const brandCss = Object.entries(brand).map(([n, v]) => `  --${k.p}-${n}: ${v};`).join('\n');
  const css = `/* ${name} - Vivi theme kit tokens. Material You roles (full M3 set), light + dark. NO yellow.
   Generated by Themes/make_tokens.mjs from tonal palettes - edit the config there, not this file.
   Light by default; dark follows the system, or force with <html data-theme="light|dark">. */
:root {
${block(roles.light)}
${brandCss}
  /* shape (corner scale) */
  --md-sys-shape-corner-extra-small: ${k.shape.xs}px;
  --md-sys-shape-corner-small: ${k.shape.sm}px;
  --md-sys-shape-corner-medium: ${k.shape.md}px;
  --md-sys-shape-corner-large: ${k.shape.lg}px;
  --md-sys-shape-corner-extra-large: ${k.shape.xl}px;
  --md-sys-shape-corner-full: 999px;
  /* type */
  --${k.p}-font-display: ${k.fonts.display};
  --${k.p}-font-body: ${k.fonts.body};
  --${k.p}-font-mono: ${k.fonts.mono};
  /* state layers (M3) */
  --md-sys-state-hover: .08; --md-sys-state-focus: .10; --md-sys-state-pressed: .10; --md-sys-state-dragged: .16;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${block(roles.dark, '    ')}
  }
}
:root[data-theme="dark"] {
${block(roles.dark)}
}
`;
  fs.writeFileSync(`${OUT}/${name}/tokens.css`, css);
  fs.writeFileSync(`${OUT}/${name}/fonts.css`, Object.entries(k.fonts).map(([role, stack]) => { const fam = stack.match(/'([^']+)'/)[1]; const file = fam.toLowerCase().replace(/ /g, '-'); const range = role === 'mono' && !['JetBrains Mono', 'Martian Mono'].includes(fam) ? '' : 'font-weight: 100 900;'; return `@font-face { font-family: '${fam}'; src: url('fonts/${file}.woff2') format('woff2'); font-display: swap; ${range || 'font-weight: 400;'} }`; }).join('\n') + '\n');
}
console.table(report.filter((r) => +r[3] < 4.5).length ? report.filter((r) => +r[3] < 4.5) : [['all pairs', 'AA ok', '', Math.min(...report.map((r) => +r[3]))]]);

